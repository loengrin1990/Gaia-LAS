import time
import urllib.request
from pathlib import Path
from unittest.mock import patch

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gaia.context_compiler import ContextCompiler, context_response_schema, local_context_model, validate_candidates
